// Helper functions for instant synchronous lookups during static export
export function getFallbackCategory(slug: string): (Category & { products: Product[] }) | null {
  const cat = FALLBACK_CATEGORIES.find((c) => c.slug === slug);
  if (!cat) return null;
  const products = FALLBACK_PRODUCTS.filter((p) => p.categoryId === cat.id);
  return { ...cat, products };
}

export function getFallbackProduct(slug: string): Product | null {
  return FALLBACK_PRODUCTS.find((p) => p.slug === slug) || null;
}
